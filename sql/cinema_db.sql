DROP DATABASE IF EXISTS cinema_db;
CREATE DATABASE cinema_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cinema_db;

-- 1. Bảng tblMember
CREATE TABLE tblMember (
    id INT(10) NOT NULL AUTO_INCREMENT,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    fullname VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NULL,
    dob DATE NULL,
    address VARCHAR(255) NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 2. Bảng tblCustomer
CREATE TABLE tblCustomer (
    customerCode VARCHAR(255) NOT NULL UNIQUE,
    tblMemberid INT(10) NOT NULL,
    PRIMARY KEY (tblMemberid),
    CONSTRAINT fk_customer_member FOREIGN KEY (tblMemberid) REFERENCES tblMember(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 3. Bảng tblStaff
CREATE TABLE tblStaff (
    staffCode VARCHAR(255) NOT NULL UNIQUE,
    position VARCHAR(255) NOT NULL,
    tblMemberid INT(10) NOT NULL,
    PRIMARY KEY (tblMemberid),
    CONSTRAINT fk_staff_member FOREIGN KEY (tblMemberid) REFERENCES tblMember(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 4. Bảng tblManagementStaff
CREATE TABLE tblManagementStaff (
    tblStafftblMemberid INT(10) NOT NULL,
    PRIMARY KEY (tblStafftblMemberid),
    CONSTRAINT fk_mgmtstaff_staff FOREIGN KEY (tblStafftblMemberid) REFERENCES tblStaff(tblMemberid) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 5. Bảng tblSaler
CREATE TABLE tblSaler (
    tblStafftblMemberid INT(10) NOT NULL,
    PRIMARY KEY (tblStafftblMemberid),
    CONSTRAINT fk_saler_staff FOREIGN KEY (tblStafftblMemberid) REFERENCES tblStaff(tblMemberid) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 6. Bảng tblCinema
CREATE TABLE tblCinema (
    cinemaCode VARCHAR(255) NOT NULL,
    cinemaName VARCHAR(255) NOT NULL,
    address VARCHAR(255) NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (cinemaCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 7. Bảng tblRoom
CREATE TABLE tblRoom (
    roomCode VARCHAR(255) NOT NULL,
    roomName VARCHAR(255) NOT NULL,
    format VARCHAR(255) NOT NULL,
    capacity INT(10) NOT NULL,
    status VARCHAR(255) NOT NULL,
    tblCinemacinemaCode VARCHAR(255) NOT NULL,
    PRIMARY KEY (roomCode),
    CONSTRAINT fk_room_cinema FOREIGN KEY (tblCinemacinemaCode) REFERENCES tblCinema(cinemaCode) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 8. Bảng tblSeat
CREATE TABLE tblSeat (
    seatCode VARCHAR(255) NOT NULL,
    rowCoord VARCHAR(255) NOT NULL,
    colCoord INT(10) NOT NULL,
    seatType VARCHAR(255) NOT NULL,
    description VARCHAR(255) NULL,
    tblRoomroomCode VARCHAR(255) NOT NULL,
    PRIMARY KEY (seatCode),
    CONSTRAINT fk_seat_room FOREIGN KEY (tblRoomroomCode) REFERENCES tblRoom(roomCode) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 9. Bảng tblMovie
CREATE TABLE tblMovie (
    movieCode VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    duration INT(10) NOT NULL,
    ageLimit VARCHAR(255) NOT NULL,
    director VARCHAR(255) NULL,
    actor VARCHAR(255) NULL,
    language VARCHAR(255) NOT NULL,
    description TEXT NULL,
    status VARCHAR(255) NOT NULL,
    poster VARCHAR(255) NULL,
    releaseDate DATE NOT NULL,
    PRIMARY KEY (movieCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 10. Bảng tblGenre
CREATE TABLE tblGenre (
    genreCode VARCHAR(255) NOT NULL,
    genreName VARCHAR(255) NOT NULL,
    PRIMARY KEY (genreCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 11. Bảng tblMovieGenre
CREATE TABLE tblMovieGenre (
    id INT(10) NOT NULL AUTO_INCREMENT,
    tblGenregenreCode VARCHAR(255) NOT NULL,
    tblMoviemovieCode VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_moviegenre_genre FOREIGN KEY (tblGenregenreCode) REFERENCES tblGenre(genreCode) ON DELETE CASCADE,
    CONSTRAINT fk_moviegenre_movie FOREIGN KEY (tblMoviemovieCode) REFERENCES tblMovie(movieCode) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 12. Bảng tblShowDate
CREATE TABLE tblShowDate (
    id INT(10) NOT NULL AUTO_INCREMENT,
    dateValue DATE NOT NULL,
    dateType VARCHAR(255) NOT NULL,
    PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 13. Bảng tblTimeSlot
CREATE TABLE tblTimeSlot (
    timeSlotCode VARCHAR(255) NOT NULL,
    startTime TIME NOT NULL,
    endTime TIME NOT NULL,
    status VARCHAR(255) NOT NULL,
    PRIMARY KEY (timeSlotCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 14. Bảng tblShowtime
CREATE TABLE tblShowtime (
    showtimeCode VARCHAR(255) NOT NULL,
    startTime TIME NOT NULL,
    endTime TIME NOT NULL,
    status VARCHAR(255) NOT NULL,
    tblMoviemovieCode VARCHAR(255) NOT NULL,
    tblShowDateid INT(10) NOT NULL,
    tblTimeSlottimeSlotCode VARCHAR(255) NOT NULL,
    tblRoomroomCode VARCHAR(255) NOT NULL,
    PRIMARY KEY (showtimeCode),
    CONSTRAINT fk_showtime_movie FOREIGN KEY (tblMoviemovieCode) REFERENCES tblMovie(movieCode) ON DELETE CASCADE,
    CONSTRAINT fk_showtime_showdate FOREIGN KEY (tblShowDateid) REFERENCES tblShowDate(id) ON DELETE CASCADE,
    CONSTRAINT fk_showtime_timeslot FOREIGN KEY (tblTimeSlottimeSlotCode) REFERENCES tblTimeSlot(timeSlotCode) ON DELETE CASCADE,
    CONSTRAINT fk_showtime_room FOREIGN KEY (tblRoomroomCode) REFERENCES tblRoom(roomCode) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 15. Bảng tblTicketPricing
CREATE TABLE tblTicketPricing (
    pricingCode VARCHAR(255) NOT NULL,
    basePrice DECIMAL(19, 0) NOT NULL,
    dateSurcharge DECIMAL(19, 0) NOT NULL,
    timeSurcharge DECIMAL(19, 0) NOT NULL,
    formatSurcharge DECIMAL(19, 0) NOT NULL,
    seatSurcharge DECIMAL(19, 0) NOT NULL,
    PRIMARY KEY (pricingCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 16. Bảng tblCardRank
CREATE TABLE tblCardRank (
    rankCode VARCHAR(255) NOT NULL,
    rankName VARCHAR(255) NOT NULL UNIQUE,
    minPoint INT(10) NOT NULL,
    discountRate DECIMAL(19, 0) NOT NULL,
    PRIMARY KEY (rankCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 17. Bảng tblMembershipCard
CREATE TABLE tblMembershipCard (
    cardCode VARCHAR(255) NOT NULL,
    issueDate DATE NOT NULL,
    point INT(10) NOT NULL,
    tblCardRankrankCode VARCHAR(255) NOT NULL,
    tblCustomertblMemberid INT(10) NOT NULL,
    PRIMARY KEY (cardCode),
    CONSTRAINT fk_card_rank FOREIGN KEY (tblCardRankrankCode) REFERENCES tblCardRank(rankCode),
    CONSTRAINT fk_card_customer FOREIGN KEY (tblCustomertblMemberid) REFERENCES tblCustomer(tblMemberid) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 18. Bảng tblTransaction
CREATE TABLE tblTransaction (
    transactionCode VARCHAR(255) NOT NULL,
    createDate DATE NOT NULL,
    createTime TIME NOT NULL,
    paymentMethod VARCHAR(255) NOT NULL,
    totalAmount DECIMAL(19, 0) NOT NULL,
    discountAmount DECIMAL(19, 0) NOT NULL,
    finalAmount DECIMAL(19, 0) NOT NULL,
    tblCustomertblMemberid INT(10) NULL,
    tblSalertblStafftblMemberid INT(10) NULL,
    PRIMARY KEY (transactionCode),
    CONSTRAINT fk_transaction_customer FOREIGN KEY (tblCustomertblMemberid) REFERENCES tblCustomer(tblMemberid),
    CONSTRAINT fk_transaction_saler FOREIGN KEY (tblSalertblStafftblMemberid) REFERENCES tblSaler(tblStafftblMemberid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 19. Bảng tblTicket
CREATE TABLE tblTicket (
    ticketCode VARCHAR(255) NOT NULL,
    ticketStatus VARCHAR(255) NOT NULL,
    tblTransactiontransactionCode VARCHAR(255) NOT NULL,
    tblTicketPricingpricingCode VARCHAR(255) NOT NULL,
    tblShowtimeshowtimeCode VARCHAR(255) NOT NULL,
    tblSeatseatCode VARCHAR(255) NOT NULL,
    PRIMARY KEY (ticketCode),
    CONSTRAINT fk_ticket_transaction FOREIGN KEY (tblTransactiontransactionCode) REFERENCES tblTransaction(transactionCode) ON DELETE CASCADE,
    CONSTRAINT fk_ticket_pricing FOREIGN KEY (tblTicketPricingpricingCode) REFERENCES tblTicketPricing(pricingCode),
    CONSTRAINT fk_ticket_showtime FOREIGN KEY (tblShowtimeshowtimeCode) REFERENCES tblShowtime(showtimeCode),
    CONSTRAINT fk_ticket_seat FOREIGN KEY (tblSeatseatCode) REFERENCES tblSeat(seatCode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

